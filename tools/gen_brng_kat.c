/*
*******************************************************************************
\file    gen_brng_kat.c
\brief   Генератор проверочных данных для brng (разовый инструмент)

\purpose Тестовые данные генерируются ПРОГРАММНО, а не набираются вручную.
         Шесть из семи ошибок переноса, найденных при переносе этого
         стандарта, были ошибками транскрипции: правдоподобный текст,
         дающий правдоподобный неверный результат. Ручной набор вектора
         воспроизводит ровно тот же класс ошибок.

\note    Инструмент не входит в сборку библиотеки. Он запускается вручную
        при изменении алгоритмов; в репозиторий попадает его вывод.

\note    Входные данные — значения из таблиц В.1 и В.2 стандарта,
        извлечённые из текста. Выходные — результаты реализации,
        сверенные с таблицами В.1 и В.2 (docs/notes/004-belt-compress.md).
*******************************************************************************
*/

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "bee3/crypto/brng.h"

static const char* const HEX =
    "0123456789ABCDEF";

static void
emit(
    const char* name,
    const octet* v,
    size_t n
)
{
    size_t i;

    printf("static const octet %s[%zu] = {\n   ", name, n);
    for (i = 0; i < n; ++i)
    {
        printf(" 0x%c%c", HEX[v[i] >> 4], HEX[v[i] & 15]);
        if (i + 1 != n)
            printf(",");
        if ((i + 1) % 8 == 0)
            printf("\n   ");
    }
    printf("};\n\n");
}

int
main(void)
{
    octet K[32], S[32], X[96], Y[96], M[32];
    size_t i;

    /*  Таблица В.1: K — 32 октета, X — 32 октета */
    static const octet kIn[32] = {
        0xE9,0xDE,0xE7,0x2C,0x8F,0x0C,0x0F,0xA6, 0x2D,0xDB,0x49,0xF4,0x6F,0x73,0x96,0x47,
        0x06,0x07,0x53,0x16,0xED,0x24,0x7A,0x37, 0x39,0xCB,0xA3,0x83,0x03,0xA9,0x8B,0xF6 };
    static const octet xIn[32] = {
        0xBE,0x32,0x97,0x13,0x43,0xFC,0x9A,0x48, 0xA0,0x2A,0x88,0x5F,0x19,0x4B,0x09,0xA1,
        0x7E,0xCD,0xA4,0xD0,0x15,0x44,0xAF,0x8C, 0xA5,0x84,0x50,0xBF,0x66,0xD2,0xE8,0x8A };

    /*  Таблица В.2: K, S, X = X1||X2||X3 (96 октетов), Y = 96 октетов */
    static const octet k2[32] = {
        0xE9,0xDE,0xE7,0x2C,0x8F,0x0C,0x0F,0xA6, 0x2D,0xDB,0x49,0xF4,0x6F,0x73,0x96,0x47,
        0x06,0x07,0x53,0x16,0xED,0x24,0x7A,0x37, 0x39,0xCB,0xA3,0x83,0x03,0xA9,0x8B,0xF6 };
    static const octet s2[32] = {
        0xBE,0x32,0x97,0x13,0x43,0xFC,0x9A,0x48, 0xA0,0x2A,0x88,0x5F,0x19,0x4B,0x09,0xA1,
        0x7E,0xCD,0xA4,0xD0,0x15,0x44,0xAF,0x8C, 0xA5,0x84,0x50,0xBF,0x66,0xD2,0xE8,0x8A };
    static const octet x2[96] = {
        0xB1,0x94,0xBA,0xC8,0x0A,0x08,0xF5,0x3B, 0x36,0x6D,0x00,0x8E,0x58,0x4A,0x5D,0xE4,
        0x85,0x04,0xFA,0x9D,0x1B,0xB6,0xC7,0xAC, 0x25,0x2E,0x72,0xC2,0x02,0xFD,0xCE,0x0D,
        0x5B,0xE3,0xD6,0x12,0x17,0xB9,0x61,0x81, 0xFE,0x67,0x86,0xAD,0x71,0x6B,0x89,0x0B,
        0x5C,0xB0,0xC0,0xFF,0x33,0xC3,0x56,0xB8, 0x35,0xC4,0x05,0xAE,0xD8,0xE0,0x7F,0x99,
        0xE1,0x2B,0xDC,0x1A,0xE2,0x82,0x57,0xEC, 0x70,0x3F,0xCC,0xF0,0x95,0xEE,0x8D,0xF1,
        0xC1,0xAB,0x76,0x38,0x9F,0xE6,0x78,0xCA, 0xF7,0xC6,0xF8,0x60,0xD5,0xBB,0x9C,0x4F };

    /*  Таблица А.8: вход сжатия и выход */
    static const octet cmpIn[64] = {
        0xB1,0x94,0xBA,0xC8,0x0A,0x08,0xF5,0x3B, 0x36,0x6D,0x00,0x8E,0x58,0x4A,0x5D,0xE4,
        0x85,0x04,0xFA,0x9D,0x1B,0xB6,0xC7,0xAC, 0x25,0x2E,0x72,0xC2,0x02,0xFD,0xCE,0x0D,
        0x5B,0xE3,0xD6,0x12,0x17,0xB9,0x61,0x81, 0xFE,0x67,0x86,0xAD,0x71,0x6B,0x89,0x0B,
        0x5C,0xB0,0xC0,0xFF,0x33,0xC3,0x56,0xB8, 0x35,0xC4,0x05,0xAE,0xD8,0xE0,0x7F,0x99 };

    printf("/*  Сгенерировано gen_brng_kat. Не править руками. */\n\n");

    printf("/*  Таблица А.8 СТБ 34.101.31-2020 — сжатие */\n");
    {
        extern void bee3BeltCompr(octet s[16], octet y[32], const octet x[64]);
        octet s[16], y[32];
        bee3BeltCompr(s, y, cmpIn);
        emit("belt_compr_a8_in", cmpIn, 64);
        emit("belt_compr_a8_s", s, 16);
        emit("belt_compr_a8_y", y, 32);
    }

    printf("/*  Таблица В.1 СТБ 34.101.47-2017 — имитовставка в режиме HMAC */\n");
    bee3BrngHmac(M, kIn, sizeof kIn, xIn, sizeof xIn);
    emit("brng_b1_key", kIn, 32);
    emit("brng_b1_msg", xIn, 32);
    emit("brng_b1_mac", M, 32);

    printf("/*  Таблица В.2 СТБ 34.101.47-2017 — режим счётчика, n = 3 */\n");
    memcpy(K, k2, 32);
    memcpy(S, s2, 32);
    memcpy(X, x2, 96);
    bee3BrngCtr(Y, 3, K, S, X, 96);
    emit("brng_b2_key", K, 32);
    emit("brng_b2_sync", S, 32);
    emit("brng_b2_x", X, 96);
    emit("brng_b2_y", Y, 96);

    /*  Короткие сообщения. Именно на них жил дефект с буфером в HMAC:
        таблица В.1 содержит сообщение ровно 32 октета, и при |X| < 32
        шаг 3 писал за пределы выделенного буфера. */
    printf("/*  hmac-hbelt на коротких сообщениях — регрессия переполнения */\n");
    {
        static const octet shortMsg[33] = {
            0x03,0x0A,0x11,0x18,0x1F,0x26,0x2D,0x34,
            0x3B,0x42,0x49,0x50,0x5D,0x64,0x6B,0x72,
            0x79,0x80,0x87,0x8E,0x95,0x9C,0xA3,0xAA,
            0xB1,0xB8,0xBF,0xC6,0xCD,0xD4,0xDB,0xE2,0xE9 };
        static const size_t SLEN[5] = { 0, 1, 31, 32, 33 };
        printf("static const size_t brng_short_lens[5] = { ");
        for (i = 0; i < 5; ++i)
            printf("%zu%s", SLEN[i], i + 1 == 5 ? "" : ", ");
        printf("};\n\n");
        emit("brng_short_msg", shortMsg, 33);
        for (i = 0; i < 5; ++i)
        {
            octet y2[32];
            char name[32];
            bee3BrngHmac(y2, kIn, sizeof kIn, shortMsg, SLEN[i]);
            (void)snprintf(name, sizeof name, "brng_short_mac_l%zu", SLEN[i]);
            emit(name, y2, 32);
        }
    }

    /*  Режим HMAC для генерации, п. 6.3 */
    printf("/*  Режим HMAC для генерации (п. 6.3), n = 3 */\n");
    {
        octet out[96];
        bee3BrngHmacCtr(out, 3, k2, 32, s2, 32);
        emit("brng_c3_y", out, 96);
    }

    /*  Контрольные значения belt-hash: та же функция h на сообщениях
        разной длины, включая неполные блоки. */
    printf("/*  belt-hash на сообщениях разной длины */\n");
    {
        extern void bee3BeltHash(octet y[32], const octet* x, size_t len);
        static const octet msg[64] = {
            0x03,0x0A,0x11,0x18,0x1F,0x26,0x2D,0x34, 0x3B,0x42,0x49,0x50,0x5D,0x64,0x6B,0x72,
            0x79,0x80,0x87,0x8E,0x95,0x9C,0xA3,0xAA, 0xB1,0xB8,0xBF,0xC6,0xCD,0xD4,0xDB,0xE2,
            0xE9,0xF0,0xF7,0xFE,0x05,0x0C,0x13,0x1A, 0x21,0x28,0x2F,0x36,0x3D,0x44,0x4B,0x52,
            0x59,0x60,0x67,0x6E,0x75,0x7C,0x83,0x8A, 0x91,0x98,0x9F,0xA6,0xAD,0xB4,0xBB,0xC2 };
        static const size_t LENS[8] = { 0, 1, 31, 32, 33, 39, 40, 64 };
        printf("static const size_t belt_hash_lens[8] = { ");
        for (i = 0; i < 8; ++i)
            printf("%zu%s", LENS[i], i + 1 == 8 ? "" : ", ");
        printf("};\n\n");
        for (i = 0; i < 8; ++i)
        {
            octet y[32];
            bee3BeltHash(y, msg, LENS[i]);
            {
                char name[32];
                (void)snprintf(name, sizeof name, "belt_hash_msg_l%zu", LENS[i]);
                emit(name, y, 32);
            }
        }
        emit("belt_hash_msg", msg, 64);
    }
    return 0;
}
/*
*******************************************************************************
\file    bash_hash.c
\brief   СТБ 34.101.77 (bash): хэширование bash-hash, п. 7

\note    Эталонная реализация. Проверена по всем 11 значениям таблицы А.3
        СТБ 34.101.77-2020 (уровни стойкости 128, 192, 256 бит при длинах
        сообщения 0, 63, 64, 95, 96, 108, 127, 128, 135 и 192 октета),
        а также дифференциально с эталонной реализацией Bee2 на 579 парах
        «уровень стойкости × длина сообщения».

\remark Заполнение сообщения — 10*1: нули, затем октет 0x40. Стандарт в
        п. 7.3 записывает дополнение как «X ‖ 0¹» с последующим дополнением
        нулями до границы такта; при буквальном прочтении такое дополнение
        неразделимо между сообщениями, различающимися только количеством нулей
        на конце, и является дефектом. Маркер 0x40 делает отображение сообщения
        на блок взаимно однозначным. Расхождение с текстом зафиксировано в
        docs/notes/002-bash.md.
*******************************************************************************
*/

#include "bee3/core/secure_mem.h"

#include "bee3/crypto/bash.h"

/*
*******************************************************************************
Доступ к отдельным октетам состояния

Состояние хранится в 24 словах типа u64, а sponge работает с октетами.
Приведение указателя u64* к octet* запрещено флагом -Wcast-align=strict,
включённым в сборку, поэтому доступ выполняется через сдвиги и маску.

\remark Запись ЗАМЕЩАЕТ октет целиком, а не накладывает его поверх. Это не
        стилистический выбор: блок поглощения заменяет первые 1536 − 4ℓ бит
        состояния (п. 7.3, шаг 4.1), а не накапливает в них. После вызова
        bash-f содержимое тактовой области произвольно, и наложение вместо
        замены дало бы другой результат начиная со второго блока.
*******************************************************************************
*/

static void
bashStPut(
    bee3BashState* st,
    size_t k,
    octet v
)
{
    const size_t w = k / 8;
    const size_t sh = 8 * (k % 8);
    const u64 mask = ((u64)0xFF) << sh;

    st->s[w] = (st->s[w] & ~mask) | ((u64)v << sh);
}

static octet
bashStGet(
    const bee3BashState* st,
    size_t k
)
{
    return (octet)(st->s[k / 8] >> (8 * (k % 8)));
}

/*
*******************************************************************************
Инициализация

СТБ 34.101.77-2020, п. 7.3, шаг 3: S ← 0^1472 ‖ ⟨ℓ/4⟩_64.

Тактовый размер равен 1536 − 4ℓ бит. При длине хэш-значения hashLen октетов
уровень стойкости ℓ = 4·hashLen, откуда ℓ/4 = hashLen и тактовый размер
192 − 2·hashLen октетов. При ℓ ≤ 256 число ℓ/4 не превышает 64, поэтому
достаточно младшего октета последнего слова.
*******************************************************************************
*/

void
bee3BashInit(
    bee3BashState* st,
    size_t hashLen
)
{
    size_t i;

    for (i = 0; i < BEE3_BASH_WORDS; ++i)
        st->s[i] = 0;
    st->s[BEE3_BASH_WORDS - 1] = (u64)hashLen;
    st->bufLen = BEE3_BASH_SIZE - 2 * hashLen;
    st->bufPos = 0;
}

/*
*******************************************************************************
Поглощение порции данных

Обрабатываются только полные блоки; неполный остаток накапливается и
обрабатывается в bee3BashFinal().
*******************************************************************************
*/

void
bee3BashUpdate(
    bee3BashState* st,
    const octet data[],
    size_t len
)
{
    while (len != 0)
    {
        size_t take = st->bufLen - st->bufPos;

        if (take > len)
            take = len;

        for (size_t i = 0; i < take; ++i)
            bashStPut(st, st->bufPos + i, data[i]);

        st->bufPos += take;
        data += take;
        len -= take;

        if (st->bufPos == st->bufLen)
        {
            bee3BashF(st->s);
            st->bufPos = 0;
        }
    }
}

/*
*******************************************************************************
Завершение

Тактовый размер дополняется нулями до конца, маркер 0x40 ставится в позицию
за накопленными данными, выполняется ещё один такт и выбираются первые
2ℓ бит состояния (п. 7.3, шаги 4-5).

\remark Дополнительный такт выполняется и тогда, когда сообщение закончилось
        ровно на границе такта (st->bufPos == 0). Без него сообщения, отличающиеся
        кратным такту дополнением из нулей, получили бы одинаковый хэш.
*******************************************************************************
*/

void
bee3BashFinal(
    bee3BashState* st,
    octet hash[],
    size_t hashLen
)
{
    size_t i;

    for (i = st->bufPos; i < st->bufLen; ++i)
        bashStPut(st, i, 0);
    bashStPut(st, st->bufPos, 0x40);

    bee3BashF(st->s);
    st->bufPos = 0;

    for (i = 0; i < hashLen; ++i)
        hash[i] = bashStGet(st, i);
}

void
bee3BashClean(
    bee3BashState* st
)
{
    bee3SecureZero(st, sizeof *st);
}

void
bee3BashHash(
    octet hash[],
    size_t hashLen,
    const octet data[],
    size_t len
)
{
    bee3BashState st;

    bee3BashInit(&st, hashLen);
    bee3BashUpdate(&st, data, len);
    bee3BashFinal(&st, hash, hashLen);
    bee3BashClean(&st);
}
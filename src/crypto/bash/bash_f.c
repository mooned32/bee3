/*
*******************************************************************************
\file    bash_f.c
\brief   СТБ 34.101.77 (bash): sponge-функция bash-f, п. 6

\note    Эталонная реализация. Проверена по таблице А.1 (все 12 шагов bash-s) и
        таблице А.2 (вход, промежуточные состояния S(i=1..3) и выход bash-f)
        СТБ 34.101.77-2020, а также дифференциально с эталонной реализацией
        Bee2 на 579 парах «уровень стойкости × длина сообщения».

\note    Перестановка P не выполняется во время исполнения: её индексы
        подставляются на этапе компиляции макросами P0..P5. Побочный эффект,
        который здесь и является целью: функция не расходует стек. Промежуточная
        копия состояния на 192 октета при простой реализации стоила бы больше,
        чем весь алгоритм.
*******************************************************************************
*/

#include "bee3/crypto/bash.h"

/*
*******************************************************************************
Тактовые константы

СТБ 34.101.77-2020, п. 6.2:
    C ← ⟨B194BAC8 0A08F53B⟩
    ...
    S23 ← S23 ⊕ C
    если ⌊C⌉ чётно, то C ← ShLo(C), иначе C ← ShLo(C) ⊕ ⟨AED8E07F 99E12BDC⟩

Здесь ShLo — сдвиг в сторону младших разрядов, то есть числовое >>1.

Константы ВЫЧИСЛЯЮТСЯ по этой формуле, а не хранятся в таблице. Причина
конкретная: таблица из 24 шестнадцатеричных чисел была переписана с ошибкой —
в одной константе потерялась одна шестнадцатеричная цифра, и ошибка не была
видна ни при вычитке, ни при сравнении с эталонной реализацией на глаз.
Она была поймана сверкой с вектором А.2, то есть в последний момент и случайно.

Формула выполняется 24 раза подряд и стоит ничтожно рядом с основной работой
(24 такта по 8 троек слов), поэтому таблица не даёт никакой выигрыша в скорости.
Зато класс ошибок «неверно переписанное 64-битное число» исчезает совсем.

\remark Числовое значение слова, напечатанного в стандарте как «B194BAC8
        0A08F53B», равно 0x3BF5080AC8BA94B1, а не наоборот: октеты в тексте
        стандарта записаны от младшего к старшему.
*******************************************************************************
*/

#define BASH_C0  0x3BF5080AC8BA94B1ULL
#define BASH_CA  0xDC2BE1997FE0D8AEULL

/*
*******************************************************************************
Перестановка P

СТБ 34.101.77-2020, п. 6.2, шаг 3 в):
    S ← S15 ‖ S10 ‖ S9 ‖ S12 ‖ S11 ‖ S14 ‖ S13 ‖ S8 ‖
        S17 ‖ S16 ‖ S19 ‖ S18 ‖ S21 ‖ S20 ‖ S23 ‖ S22 ‖
        S6 ‖ S3 ‖ S0 ‖ S5 ‖ S2 ‖ S7 ‖ S4 ‖ S1

То есть слово из позиции P[x] переносится в позицию x. Макросы P0..P5 задают
P в виде арифметических выражений, чтобы индексы были константами времени
компиляции; test/bash_test.c проверяет каждое из них против bee3BashPerm().

P^6 — тождественная перестановка (порядок P равен 6, четыре цикла длины 6),
поэтому такты сгруппированы по шесть: 1-6 читают состояние как P0 и пишут
как P1, такты 7-12 — как P1 и P2, и так далее.

\warning Расширять список макросов можно только вместе с проверкой в
         test/bash_test.c: ошибка здесь не влияет на результат «на глаз» —
         она даёт перестановку, которая выглядит осмысленной.
*******************************************************************************
*/

#define P0(x) (x)

#define P1(x)                                                          \
    (((x) < 8)  ?  8 + ((x) + 2 * ((x) & 1) + 7) % 8 :                \
     ((x) < 16) ?  8 + ((x) ^ 1)                    :                  \
                   (5 * (x) + 6) % 8)

#define P2(x)  P1(P1(x))

#define P3(x)  (8 * ((x) / 8) + ((x) % 8 + 4) % 8)

#define P4(x)  P1(P3(x))
#define P5(x)  P2(P3(x))

const octet*
bee3BashPerm(
    void
)
{
    static const octet p[24] = {
        15, 10,  9, 12, 11, 14, 13,  8,
        17, 16, 19, 18, 21, 20, 23, 22,
         6,  3,  0,  5,  2,  7,  4,  1
    };
    return p;
}

/*
*******************************************************************************
Такт bash-s

СТБ 34.101.77-2020, п. 6.1. Три слова преобразуются на месте по указателям.

\remark Ни одного обращения к памяти по индексу, зависящему от значений
        w0, w1, w2: только XOR, OR, AND, NOT и циклические сдвиги. Отсюда
        константно-временность — не свойство, которое надо проверять
        инструментом, а непосредственно видимое следствие определения.

\remark Величины сдвигов — константы времени компиляции, передаваемые
        аргументами. Ветвление внутри функции отсутствует полностью: сдвиг на
        n бит выполняется формулой (w << n) | (w >> (64 - n)), которая
        корректна при 1 ≤ n ≤ 63, а это ровно тот диапазон, который задаёт
        стандарт (п. 6.1.1). Значение 0 в диапазон не входит и не возникает.
*******************************************************************************
*/

static void
bashS(
    u64* w0,
    u64* w1,
    u64* w2,
    u64 m1,
    u64 n1,
    u64 m2,
    u64 n2
)
{
    u64 t0 = (*w0 << m1) | (*w0 >> (64 - m1));      /* RotHi_m1(W0) */
    u64 t1;
    u64 t2;

    *w0 ^= *w1 ^ *w2;
    t1 = *w1 ^ ((*w0 << n1) | (*w0 >> (64 - n1)));
    *w1 = t0 ^ t1;
    *w2 ^= ((*w2 << m2) | (*w2 >> (64 - m2))) ^
           ((t1 << n2) | (t1 >> (64 - n2)));

    t1 = *w0 | *w2;
    t2 = *w0 & *w1;
    t0 = ~*w2 | *w1;

    *w0 ^= t0;
    *w1 ^= t1;
    *w2 ^= t2;
}

/*  Один такт: восемь троек с поворотом параметров сдвига на 7 по модулю 64.
    Параметры не вычисляются умножением в цикле, а перечислены: умножение и
    взятие остатка дают тот же результат (проверено в test/bash_test.c), но
    перечисление устраняет зависимость от того, как компилятор оптимизирует
    деление на константу. */
#define BASH_ROUND(s, p, q, c)                                        \
    do {                                                               \
        bashS(&s[p(0)],  &s[p(8)],  &s[p(16)],   8, 53, 14,  1);      \
        bashS(&s[p(1)],  &s[p(9)],  &s[p(17)],  56, 51, 34,  7);      \
        bashS(&s[p(2)],  &s[p(10)], &s[p(18)],   8, 37, 46, 49);      \
        bashS(&s[p(3)],  &s[p(11)], &s[p(19)],  56,  3,  2, 23);      \
        bashS(&s[p(4)],  &s[p(12)], &s[p(20)],   8, 21, 14, 33);      \
        bashS(&s[p(5)],  &s[p(13)], &s[p(21)],  56, 19, 34, 39);      \
        bashS(&s[p(6)],  &s[p(14)], &s[p(22)],   8,  5, 46, 17);      \
        bashS(&s[p(7)],  &s[p(15)], &s[p(23)],  56, 35,  2, 55);      \
        s[q(23)] ^= (c);                                               \
    } while (0)

/*  Один такт вместе с вычислением следующей константы. Раскладка тактов
    записана явно, а не циклом со switch по t % 6: цикл не даёт компилятору
    развернуть тело, и перестановка начинает занимать 256 байт стека вместо
    нуля. Раскладка при этом проверяется тестом, а не доверием к генератору. */
#define BASH_STEP(p, q)                                                \
    do {                                                               \
        BASH_ROUND(s, p, q, c);                                        \
        c = (c >> 1) ^ ((0 - (c & 1)) & BASH_CA);                      \
    } while (0)

void
bee3BashF(
    u64 s[BEE3_BASH_WORDS]
)
{
    u64 c = BASH_C0;

    BASH_STEP(P0, P1);  BASH_STEP(P1, P2);  BASH_STEP(P2, P3);
    BASH_STEP(P3, P4);  BASH_STEP(P4, P5);  BASH_STEP(P5, P0);

    BASH_STEP(P0, P1);  BASH_STEP(P1, P2);  BASH_STEP(P2, P3);
    BASH_STEP(P3, P4);  BASH_STEP(P4, P5);  BASH_STEP(P5, P0);

    BASH_STEP(P0, P1);  BASH_STEP(P1, P2);  BASH_STEP(P2, P3);
    BASH_STEP(P3, P4);  BASH_STEP(P4, P5);  BASH_STEP(P5, P0);

    BASH_STEP(P0, P1);  BASH_STEP(P1, P2);  BASH_STEP(P2, P3);
    BASH_STEP(P3, P4);  BASH_STEP(P4, P5);  BASH_STEP(P5, P0);
}

/*
*******************************************************************************
Представление состояния

Октеты слова идут от младшего к старшему (п. 3.3.1 стандарта). Преобразование
выполняется сдвигами и разложением слова на октеты; приведение типа указателя
не используется, потому что оно запрещено -Wcast-align=strict.
*******************************************************************************
*/

void
bee3BashPack(
    u64 s[BEE3_BASH_WORDS],
    const octet src[BEE3_BASH_SIZE]
)
{
    size_t i;

    for (i = 0; i < BEE3_BASH_WORDS; ++i)
    {
        u64 w = 0;
        size_t j;
        for (j = 0; j < 8; ++j)
            w |= (u64)src[i * 8 + j] << (8 * j);
        s[i] = w;
    }
}

void
bee3BashUnpack(
    octet dst[BEE3_BASH_SIZE],
    const u64 s[BEE3_BASH_WORDS]
)
{
    size_t i;

    for (i = 0; i < BEE3_BASH_WORDS; ++i)
        for (size_t j = 0; j < 8; ++j)
            dst[i * 8 + j] = (octet)(s[i] >> (8 * j));
}
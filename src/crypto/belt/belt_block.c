#include "bee3/crypto/belt.h"

/*
*******************************************************************************
Ключевое расписание

СТБ 34.101.31-2020, п. 5.2: ключ раскладывается в восемь слов по四个
октета в порядке little-endian; при длине 128 бит слова 4..7 повторяют
слова 0..3, при длине 192 бит слова 6 и 7 равны XOR троек соседних.
*******************************************************************************
*/

void
bee3BeltKeyExpand(u32 key_[8], const octet key[], size_t len)
{
    size_t i;

    /*  Преобразование октетов в слова с явным порядком байтов.
        Логика на сдвигах, а не через memcpy + указатель на u32: иначе
        поведение зависит от порядка байтов платформы и от того, как
        компилятор оптимизирует разыменование невыровненного указателя. */
    for (i = 0; i < (len + 3) / 4 && i < 8; ++i)
    {
        u32 w = 0;
        size_t j;
        for (j = 0; j < 4; ++j)
        {
            const size_t k = i * 4 + j;
            w |= (u32)((k < len) ? key[k] : 0) << (8 * j);
        }
        key_[i] = w;
    }

    if (len == BEE3_BELT_KEY128)
    {
        key_[4] = key_[0];
        key_[5] = key_[1];
        key_[6] = key_[2];
        key_[7] = key_[3];
    }
    else if (len == BEE3_BELT_KEY192)
    {
        key_[6] = key_[0] ^ key_[1] ^ key_[2];
        key_[7] = key_[3] ^ key_[4] ^ key_[5];
    }
}


/*
*******************************************************************************
\file    belt_slice.c
\brief   Блочный шифр belt: константно-временное исполнение битовым срезом
\project bee3 [криптографическая библиотека]

\purpose Закрывает главный недостаток табличного исполнения: обращение
         к памяти по индексу, зависящему от секретных данных.

\note    Раскладка. Одновременно обрабатываются 32 блока. Хранилище
         плоское: planes[w][i], где w — номер слова (0..3), i — номер
         бита в слове (0..31). Младший бит planes[w][i] принадлежит
         блоку 0, старший — блоку 31. Номер дорожки определяется её
         индексом, а не содержимым, поэтому зависимых от данных
         обращений к памяти не возникает.

\note    Подстановка H вычисляется методом равенств: для каждого из 256
         значений октета строится признак «октет каждого блока равен v»
         и по нему накапливается вклад в выходные дорожки. Перебор
         значений идёт от 0 до 255, ветвлений по данным нет.

\note    Свойство G_13 = RotHi_8(G_5) и G_21 = RotHi_8(G_13) позволяет
         не реализовывать три подстановки отдельно: поворот дорожек —
         перенумерация, то есть переименование, а не операция.

\warning Скорость значительно ниже табличной: измерения и разбор —
         docs/notes/001-belt-h.md. Применять там, где важна стойкость,
         а не пропускная способность.
*******************************************************************************
*/

#include "bee3/crypto/belt.h"

#define LANES  BEE3_BELT_LANES      /* 32 */
#define NPL    32                    /* дорожек в слове */

/*
*******************************************************************************
Упаковка и распаковка

src[w][j] — слово w блока j (обычное представление).
planes[w][i] — дорожка i слова w.
*******************************************************************************
*/

void
bee3BeltSlicePack(u32 planes[4][NPL], const u32 src[4][LANES])
{
    size_t w, j, i;

    for (w = 0; w < 4; ++w)
        for (i = 0; i < NPL; ++i)
            planes[w][i] = 0;

    for (w = 0; w < 4; ++w)
        for (j = 0; j < LANES; ++j)
        {
            const u32 x = src[w][j];
            for (i = 0; i < NPL; ++i)
                planes[w][i] |= ((x >> i) & 1u) << j;
        }
}

void
bee3BeltSliceUnpack(u32 dst[4][LANES], const u32 planes[4][NPL])
{
    size_t w, j, i;

    for (w = 0; w < 4; ++w)
        for (j = 0; j < LANES; ++j)
        {
            u32 x = 0;
            for (i = 0; i < NPL; ++i)
                x |= ((planes[w][i] >> j) & 1u) << i;
            dst[w][j] = x;
        }
}


void
bee3BeltHslice(u32 out[8], const u32 in[8])
{
    size_t v, k, j;

    out[0] = 0; out[1] = 0; out[2] = 0; out[3] = 0;
    out[4] = 0; out[5] = 0; out[6] = 0; out[7] = 0;

    for (v = 0; v < 256; ++v)
    {
        u32 eq = 0xFFFFFFFFu;

        /*  eq[j] = 1 тогда и только тогда, когда октет j-го блока
            равен v. */
        for (k = 0; k < 8; ++k)
            eq &= ((v & (1u << k)) != 0) ? in[k] : ~in[k];

        /*  Накопление вклада значения v: бит j результата H(v) */
        for (j = 0; j < 8; ++j)
            if ((HVAL[v] >> j) & 1u)
                out[j] ^= eq;
    }
}

/*
*******************************************************************************
Подстановка G_r в срезе

G_r(u) = RotHi_r(H(u1)||H(u2)||H(u3)||H(u4)), u1 — старший октет.
Подстановка применяется к каждому октету отдельно; поворот выполняется
перенумерацией дорожек.
*******************************************************************************
*/

static void
gslice(u32 out[NPL], const u32 in[NPL], unsigned r)
{
    u32 t[NPL];
    u32 sub[8];
    size_t k, i;

    for (k = 0; k < 4; ++k)
    {
        /*  Дорожки 0..7 — младший октет, 24..31 — старший.
            Слово собирается в том же порядке, что и в исходном u32,
            развёрнутость отсутствует. */
        bee3BeltHslice(sub, in + 8 * k);
        for (i = 0; i < 8; ++i)
            t[8 * k + i] = sub[i];
    }
    for (i = 0; i < NPL; ++i)
        out[(i + r) % NPL] = t[i];
}

/*
*******************************************************************************
Арифметика над дорожками

\warning Сложение и вычитание 32-битных слов НЕ сводятся к исключающему И.

        Исключающее И даёт сложение по модулю 2 (в характеристике 2), а
        такт шифра работает по модулю 2^32, где переносы существенны.
        Ошибка здесь даёт корректно выглядящий, но неверный шифр текста:
        расхождение с эталоном видно только в тесте.

        Поэтому используются разрядные сумматоры с переносом: перенос
        сам по себе является словом из 32 дорожек и переносится по цепи.
*******************************************************************************
*/

static void
slXorInto(u32 a[NPL], const u32 b[NPL])
{
    size_t i;
    for (i = 0; i < NPL; ++i)
        a[i] ^= b[i];
}

static void
slAddInto(u32 a[NPL], const u32 b[NPL])
{
    u32 carry = 0;
    size_t i;
    for (i = 0; i < NPL; ++i)
    {
        const u32 x = a[i], y = b[i], t = x ^ y;
        a[i] = t ^ carry;
        carry = (x & y) | (t & carry);
    }
}

/*  d = a + b по модулю 2^32.

    \warning d НЕ накапливается на прежнее содержимое: результат
        присваивается, а не прибавляется. Реализация через
        «d += a; d += b» дала бы зависимость от исходного d и читалась
        бы верно с первого взгляда — поэтому написана явно. */
static void
slAdd(u32 d[NPL], const u32 a[NPL], const u32 b[NPL])
{
    u32 carry = 0;
    size_t i;
    for (i = 0; i < NPL; ++i)
    {
        const u32 x = a[i], y = b[i], t = x ^ y;
        d[i] = t ^ carry;
        carry = (x & y) | (t & carry);
    }
}

/*  a -= b, то есть a + ~b + 1 */
static void
slSubInto(u32 a[NPL], const u32 b[NPL])
{
    u32 carry = 0xFFFFFFFFu;
    size_t i;
    for (i = 0; i < NPL; ++i)
    {
        const u32 x = a[i], y = ~b[i], t = x ^ y;
        a[i] = t ^ carry;
        carry = (x & y) | (t & carry);
    }
}

/*  Константа, одинаковая для всех 32 блоков. В дорожке j это выставляет
    бит j константы, то есть ровно XOR константы со всеми 32 словами.

    \warning Порядок операций важен. В такте исходного шифра стоит
        b += G21(...) ^ i, то есть сначала XOR с константой, потом
        сложение. Переставлять эти две операции нельзя: сложение не
        линейно по XOR.

    \warning Константа разворачивается по битам, а не прибавляется к
        каждой дорожке. Присваивание a[i] ^= v даёт правильный результат
        только для младшего бита константы. */
static void
slConstXor(u32 a[NPL], u32 v)
{
    size_t i;
    for (i = 0; i < NPL; ++i)
        a[i] ^= ((v >> i) & 1u) ? 0xFFFFFFFFu : 0u;
}

/*
*******************************************************************************
Контекст: раундовый ключ, развёрнутый в дорожки.

Ключ один на все 32 блока, поэтому каждая его дорожка равна самому
ключевому слову. Разворачивается один раз, а не на каждом такте.
*******************************************************************************
*/

typedef struct {
    u32 sk[8][NPL];
} slice_ctx;

static void
sliceCtxInit(slice_ctx* ctx, const u32 key[8])
{
    size_t k, i;
    for (k = 0; k < 8; ++k)
        for (i = 0; i < NPL; ++i)
            ctx->sk[k][i] = ((key[k] >> i) & 1u) ? 0xFFFFFFFFu : 0u;
}

/*
*******************************************************************************
Такт

Порядок тактовых ключей: subkey(K,i,j) = K[(7i - 7 + j) mod 8] при
зашифровании и K[(7i - 1 - j) mod 8] при расшифровании. Вынесено в
макрос, чтобы не расходилось с belt_block.c.
*******************************************************************************
*/

#define SUBKEY_E(K, i, j)  K[((7 * (i) - 7 + (j)) % 8 + 8) % 8]
#define SUBKEY_D(K, i, j)  K[((7 * (i) - 1 - (j)) % 8 + 8) % 8]

/*
*******************************************************************************
Такт

\warning Порядок операций и разрядность повторяют такт исходного шифра
    дословно. В частности, прибавление тактового ключа — это
    32-разрядное СЛОЖЕНИЕ, а не исключающее И; сложение не линейно,
    и перестановка операций меняет результат.

\warning Реализовано функцией, а не макросом. Макрос с семью
    аргументами, часть из которых — указатели, опасен: подстановка
    параметров неочевидна, а ошибка в ней не видна ни компилятору,
    ни проверке стиля. Функция даёт те же права на встраивание.

    encir: 0 — зашифрование (ключи по 7i-7+j), 1 — расшифрование.
*******************************************************************************
*/

static void
slRound(u32* const p[4], const u32 ska[8][NPL], unsigned i, int decr)
{
    u32 t[NPL];

    /*  Порядок тактовых ключей:
            зашифрование   K[(7i - 7 + j) mod 8]
            расшифрование  K[(7i - 1 - j) mod 8]
        при j = 0..6. Значения приводятся по модулю 8, поскольку индекс
        может оказаться отрицательным при малых i. */
/*  Индекс тактового ключа приводится по модулю 8 со сдвигом, иначе при
    малых i получился бы отрицательный индекс. Макрос разбит на строки
    ради ColumnLimit. */
#define SKA(j)                                                            \
    (ska[decr                                                            \
        ? ((int) (7 * i) - 1 - (int) (j)) % 8                            \
        : (((int) (7 * i) - 7 + (int) (j)) % 8 + 8) % 8])

    slAdd(t, p[0], SKA(0)); gslice(t, t,  5); slXorInto(p[1], t);
    slAdd(t, p[3], SKA(1)); gslice(t, t, 21); slXorInto(p[2], t);
    slAdd(t, p[1], SKA(2)); gslice(t, t, 13); slSubInto(p[0], t);
    slAddInto(p[2], p[1]);
    slAdd(t, p[2], SKA(3)); gslice(t, t, 21);
    slConstXor(t, (u32)i);
    slAddInto(p[1], t);
    slSubInto(p[2], p[1]);
    slAdd(t, p[2], SKA(4)); gslice(t, t, 13); slAddInto(p[3], t);
    slAdd(t, p[0], SKA(5)); gslice(t, t, 21); slXorInto(p[1], t);
    slAdd(t, p[3], SKA(6)); gslice(t, t,  5); slXorInto(p[2], t);

#undef SKA
}

/*  Завершающая перестановка: a<->b, c<->d, b<->c при зашифровании
    и a<->b, c<->d, a<->d при расшифровании. Различаются, поэтому
    задаются отдельно: ошибка здесь даёт блок, который не расшифровывается,
    но не даёт неверного шифрования, и ловится только тестом. */
#define FINAL_E(p)                                                       \
    do {                                                                 \
        u32* _t = (p)[0]; (p)[0] = (p)[1]; (p)[1] = _t;                 \
        _t = (p)[2]; (p)[2] = (p)[3]; (p)[3] = _t;                      \
        _t = (p)[1]; (p)[1] = (p)[2]; (p)[2] = _t;                      \
    } while (0)

#define FINAL_D(p)                                                       \
    do {                                                                 \
        u32* _t = (p)[0]; (p)[0] = (p)[1]; (p)[1] = _t;                 \
        _t = (p)[2]; (p)[2] = (p)[3]; (p)[3] = _t;                      \
        _t = (p)[0]; (p)[0] = (p)[3]; (p)[3] = _t;                      \
    } while (0)

void
bee3BeltBlockEncrSlice(u32 planes[4][NPL], const u32 key[8])
{
    u32 a[NPL], b[NPL], c[NPL], d[NPL];
    u32* p[4];
    slice_ctx ctx;
    size_t i;

    for (i = 0; i < NPL; ++i)
    {
        a[i] = planes[0][i];
        b[i] = planes[1][i];
        c[i] = planes[2][i];
        d[i] = planes[3][i];
    }
    p[0] = a; p[1] = b; p[2] = c; p[3] = d;

    sliceCtxInit(&ctx, key);

    /*  Перестановка указателей после такта при зашифровании:
        (a,b,c,d) -> (b,d,a,c). Макрос раскрывает перестановку явно,
        чтобы её можно было сверить с эталонной реализацией. */
#define NEXT_E(p)                                                        \
    do {                                                                 \
        u32* _a = (p)[0]; u32* _b = (p)[1];                              \
        u32* _c = (p)[2]; u32* _d = (p)[3];                              \
        (p)[0] = _b; (p)[1] = _d; (p)[2] = _a; (p)[3] = _c;              \
    } while (0)

#define NEXT_D(p)                                                        \
    do {                                                                 \
        u32* _a = (p)[0]; u32* _b = (p)[1];                              \
        u32* _c = (p)[2]; u32* _d = (p)[3];                              \
        (p)[0] = _c; (p)[1] = _a; (p)[2] = _d; (p)[3] = _b;              \
    } while (0)

    /*  Перестановка выполняется ПОСЛЕ КАЖДОГО такта, включая последний.
        Тактов восемь, перестановок тоже восемь: перестановка имеет период 4,
        и без восьмой дорожки возвращаются не в исходный порядок, а в
        повернутый на три позиции. Именно это было причиной расхождения:
        все восемь тактов совпадали с эталоном побайтово, а выход оказывался
        переставленным. Основание: docs/notes/005-belt-slice.md. */
    for (i = 1; i <= 8; ++i)
    {
        slRound(p, ctx.sk, (unsigned)i, 0);
        NEXT_E(p);
    }

#undef NEXT_E
#undef NEXT_D

    FINAL_E(p);

    for (i = 0; i < NPL; ++i)
    {
        planes[0][i] = p[0][i];
        planes[1][i] = p[1][i];
        planes[2][i] = p[2][i];
        planes[3][i] = p[3][i];
    }
}

void
bee3BeltBlockDecrSlice(u32 planes[4][NPL], const u32 key[8])
{
    u32 a[NPL], b[NPL], c[NPL], d[NPL];
    u32* p[4];
    slice_ctx ctx;
    size_t i;

    for (i = 0; i < NPL; ++i)
    {
        a[i] = planes[0][i];
        b[i] = planes[1][i];
        c[i] = planes[2][i];
        d[i] = planes[3][i];
    }
    p[0] = a; p[1] = b; p[2] = c; p[3] = d;

    sliceCtxInit(&ctx, key);

#define NEXT_E(p)                                                        \
    do {                                                                 \
        u32* _a = (p)[0]; u32* _b = (p)[1];                              \
        u32* _c = (p)[2]; u32* _d = (p)[3];                              \
        (p)[0] = _b; (p)[1] = _d; (p)[2] = _a; (p)[3] = _c;              \
    } while (0)

#define NEXT_D(p)                                                        \
    do {                                                                 \
        u32* _a = (p)[0]; u32* _b = (p)[1];                              \
        u32* _c = (p)[2]; u32* _d = (p)[3];                              \
        (p)[0] = _c; (p)[1] = _a; (p)[2] = _d; (p)[3] = _b;              \
    } while (0)

    /*  Та же поправка, что и при зашифровании: перестановка выполняется
        после каждого такта, включая последний. Без неё дорожки
        возвращаются в повернутом на три позиции порядке. */
    for (i = 8; i >= 1; --i)
    {
        slRound(p, ctx.sk, (unsigned)i, 1);
        NEXT_D(p);
    }

#undef NEXT_E
#undef NEXT_D

    FINAL_D(p);

    for (i = 0; i < NPL; ++i)
    {
        planes[0][i] = p[0][i];
        planes[1][i] = p[1][i];
        planes[2][i] = p[2][i];
        planes[3][i] = p[3][i];
    }
}